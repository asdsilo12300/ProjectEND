const translatedText = new WeakMap()
const originalText = new WeakMap()
const translatedAttributes = new WeakMap()
const originalAttributes = new WeakMap()
const translatedAttributeNames = ['placeholder', 'aria-label', 'title', 'alt']
const skippedTags = new Set(['SCRIPT', 'STYLE', 'NOSCRIPT'])

let activeLanguage = 'en'
let observer = null

function translatedPhrase(source) {
  const normalized = String(source ?? '').replace(/\s+/g, ' ').trim()
  if (!normalized) return source
  if (Object.prototype.hasOwnProperty.call(thaiMessages, normalized)) return thaiMessages[normalized]

  for (const [pattern, replacement] of thaiPatterns) {
    if (pattern.test(normalized)) return normalized.replace(pattern, replacement)
  }

  return source
}

function withOriginalWhitespace(source, translated) {
  if (translated === source) return source
  const leading = source.match(/^\s*/)?.[0] ?? ''
  const trailing = source.match(/\s*$/)?.[0] ?? ''
  return `${leading}${String(translated).trim()}${trailing}`
}

function translateTextNode(node) {
  if (!node?.parentElement || skippedTags.has(node.parentElement.tagName)) return

  const current = node.nodeValue ?? ''

  if (activeLanguage === 'th') {
    if (translatedText.get(node) === current) return
    const translated = withOriginalWhitespace(current, translatedPhrase(current))
    if (translated === current) return
    originalText.set(node, current)
    translatedText.set(node, translated)
    node.nodeValue = translated
    return
  }

  if (originalText.has(node)) {
    const original = originalText.get(node)
    if (current === translatedText.get(node)) node.nodeValue = original
    originalText.delete(node)
    translatedText.delete(node)
  }
}

function mapFor(store, element) {
  if (!store.has(element)) store.set(element, new Map())
  return store.get(element)
}

function translateAttribute(element, name) {
  if (!element.hasAttribute(name)) return
  const current = element.getAttribute(name) ?? ''
  const translatedMap = mapFor(translatedAttributes, element)
  const originalMap = mapFor(originalAttributes, element)

  if (activeLanguage === 'th') {
    if (translatedMap.get(name) === current) return
    const translated = translatedPhrase(current)
    if (translated === current) return
    originalMap.set(name, current)
    translatedMap.set(name, translated)
    element.setAttribute(name, translated)
    return
  }

  if (originalMap.has(name)) {
    if (current === translatedMap.get(name)) element.setAttribute(name, originalMap.get(name))
    originalMap.delete(name)
    translatedMap.delete(name)
  }
}

function translateElement(element) {
  if (!element || skippedTags.has(element.tagName)) return
  translatedAttributeNames.forEach((name) => translateAttribute(element, name))
  element.childNodes.forEach((child) => {
    if (child.nodeType === Node.TEXT_NODE) translateTextNode(child)
    if (child.nodeType === Node.ELEMENT_NODE) translateElement(child)
  })
}

function translateDocument() {
  if (document.body) translateElement(document.body)
}

function startObserver() {
  if (observer || !document.documentElement) return

  observer = new MutationObserver((mutations) => {
    mutations.forEach((mutation) => {
      if (mutation.type === 'characterData') translateTextNode(mutation.target)
      if (mutation.type === 'attributes') translateAttribute(mutation.target, mutation.attributeName)
      mutation.addedNodes?.forEach((node) => {
        if (node.nodeType === Node.TEXT_NODE) translateTextNode(node)
        if (node.nodeType === Node.ELEMENT_NODE) translateElement(node)
      })
    })
  })

  observer.observe(document.documentElement, {
    attributes: true,
    attributeFilter: translatedAttributeNames,
    characterData: true,
    childList: true,
    subtree: true,
  })
}

export function setAppLanguage(language) {
  activeLanguage = language === 'th' ? 'th' : 'en'
  document.documentElement.lang = activeLanguage
  startObserver()
  translateDocument()
}

export function getAppLanguage() {
  return activeLanguage
}
