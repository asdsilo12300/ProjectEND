function preserveWhitespace(value, translated) {
  const leading = value.match(/^\s*/)?.[0] ?? ''
  const trailing = value.match(/\s*$/)?.[0] ?? ''
  return `${leading}${translated}${trailing}`
}

export function adminText(language, value) {
  if (language !== 'th' || typeof value !== 'string') return value
  const source = value.trim()
  if (!source) return value
  const exact = thai[source]
  if (exact) return preserveWhitespace(value, exact)
  for (const [pattern, replace] of patterns) {
    const match = source.match(pattern)
    if (match) return preserveWhitespace(value, replace(match))
  }
  return value
}

const originalText = new WeakMap()
const originalAttributes = new WeakMap()
const translatedAttributes = ['aria-label', 'placeholder', 'title']

function localizeNode(root, language) {
  if (!root) return
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT)
  const nodes = []
  while (walker.nextNode()) nodes.push(walker.currentNode)

  nodes.forEach((node) => {
    if (node.parentElement?.closest('[data-admin-no-translate], script, style, iframe')) return
    const remembered = originalText.get(node)
    if (language === 'th') {
      const expected = remembered == null ? null : adminText('th', remembered)
      if (remembered == null || node.data !== expected) originalText.set(node, node.data)
      node.data = adminText('th', originalText.get(node))
    } else if (remembered != null) {
      // React components that translate from language state have already rendered
      // the new English value by this point. Only restore text that is still the
      // Thai DOM translation produced by this fallback translator; otherwise the
      // remembered value can overwrite React and make switching appear stuck.
      if (node.data === adminText('th', remembered)) node.data = remembered
      originalText.delete(node)
    }
  })

  root.querySelectorAll('*').forEach((element) => {
    let remembered = originalAttributes.get(element)
    translatedAttributes.forEach((attribute) => {
      if (!element.hasAttribute(attribute)) return
      if (!remembered) { remembered = {}; originalAttributes.set(element, remembered) }
      const current = element.getAttribute(attribute)
      if (language === 'th') {
        const expected = remembered[attribute] == null ? null : adminText('th', remembered[attribute])
        if (remembered[attribute] == null || current !== expected) remembered[attribute] = current
        element.setAttribute(attribute, adminText('th', remembered[attribute]))
      } else if (remembered[attribute] != null) {
        if (current === adminText('th', remembered[attribute])) {
          element.setAttribute(attribute, remembered[attribute])
        }
        delete remembered[attribute]
      }
    })
  })
}

export function useAdminLanguage(language, rootRef) {
  useLayoutEffect(() => {
    const root = rootRef.current
    if (!root) return undefined
    let queued = false
    let cancelled = false
    const observer = new MutationObserver(() => {
      if (queued || cancelled) return
      queued = true
      queueMicrotask(() => {
        if (cancelled) return
        queued = false
        observer.disconnect()
        localizeNode(root, language)
        if (!cancelled) {
          observer.observe(root, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: translatedAttributes })
        }
      })
    })
    localizeNode(root, language)
    observer.observe(root, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: translatedAttributes })
    return () => {
      cancelled = true
      observer.disconnect()
    }
  }, [language, rootRef])
}
